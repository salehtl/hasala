#!/usr/bin/env python3
"""Builds the bundled merchant dictionary (spec 03c §8.5) from a CSV.

    python3 -I ios/tools/dictionary/build-dictionary.py ios/tools/dictionary/seed-v1.csv BUNDLE

Writes ios/HasalaCore/Sources/HasalaCore/Resources/merchant-dictionary.json and
Categorize/DictionaryManifest.swift. Fails (no silent mapping) on an unknown
category or one that is neither spending nor the built-in transfer, a pattern that is not already canonical (lower-case,
single spaces), a pattern under its floor or over 64 scalars, or a duplicate
(match, pattern).

The seed is a hand-curated list of public brand names for the beta
(TODO(03c §8.5.2): replace with the operator's corpus export through the Swift
generator). It holds merchant patterns and categories only, no personal data.
"""
import csv, hashlib, json, os, sys

SPENDING = ["rent","utilities","groceries","transport","healthcare","insurance","dining","entertainment",
            "shopping","travel","subscriptions","savings","investments","debt"]
CATEGORIES = SPENDING + ["transfer"]
ORDER = {"exact": 0, "starts_with": 1, "contains": 2}
FLOOR = {"exact": 2, "starts_with": 3, "contains": 4}

def main():
    src, bundle = sys.argv[1], sys.argv[2]
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    rows, seen = [], set()
    with open(src, newline="", encoding="utf-8") as f:
        for r in csv.DictReader(f):
            m, p, c, d = r["match"], r["pattern"], r["category"], r["display"]
            assert m in ORDER, f"match {m!r}"
            assert c in CATEGORIES, f"category {c!r}"
            # Canonical already: no upper-case, no leading, trailing or double spaces.
            assert p == " ".join(p.split()), f"spaces {p!r}"
            assert p == p.lower(), f"case {p!r}"
            n = len(p)
            assert FLOOR[m] <= n <= 64, f"length {p!r}"
            assert (m, p) not in seen, f"duplicate {m} {p}"
            seen.add((m, p))
            e = {"m": m, "p": p, "c": c}
            if d:
                assert 1 <= len(d) <= 64 and d == d.strip(), f"display {d!r}"
                e["d"] = d
            rows.append(e)
    rows.sort(key=lambda e: (ORDER[e["m"]], [ord(ch) for ch in e["p"]]))
    doc = {"format": "hasala.merchant-dictionary", "format_version": 1, "bundle": bundle, "taxonomy": 1, "entries": rows}
    text = json.dumps(doc, ensure_ascii=False, separators=(",", ":")) + "\n"
    data = text.encode("utf-8")
    assert len(data) <= 2 * 1024 * 1024
    out = os.path.join(root, "HasalaCore/Sources/HasalaCore/Resources/merchant-dictionary.json")
    with open(out, "wb") as f:
        f.write(data)
    digest = hashlib.sha256(data).hexdigest()
    swift = f"""// Generated by ios/tools/dictionary/build-dictionary.py; do not edit (spec 03c §8.5.2).
public enum DictionaryManifest {{
  public static let bundle = "{bundle}"
  public static let sha256 = "{digest}"
  public static let entries = {len(rows)}
}}
"""
    with open(os.path.join(root, "HasalaCore/Sources/HasalaCore/Categorize/DictionaryManifest.swift"), "w") as f:
        f.write(swift)
    print(f"{len(rows)} entries, sha256 {digest}")

main()
