// Copies the published seed templates (server/internal/tmpl/seed/*.json) into the app bundle's
// resources (ios/HasalaCore/Sources/HasalaCore/Resources/templates/) and writes
// TemplatesManifest.swift beside them: {file, id, version, sha256} per template (spec 04 §4.6).
//
//   swift ios/tools/templates/sync.swift           # copy and rewrite the manifest
//   swift ios/tools/templates/sync.swift --check   # exit 1 if either has drifted
//
// Run from the repository root. The copies are byte-for-byte (no re-encoding: the Arabic
// anchors were extracted from v1's source and must never pass through a keyboard or a JSON
// re-serializer). CoreTemplateTests also compares the bundle with the seed directory, so a
// drift fails `swift test` even when nobody runs this script.
import CryptoKit
import Foundation

let seedDir = "server/internal/tmpl/seed"
let outDir = "ios/HasalaCore/Sources/HasalaCore/Resources/templates"
let manifestPath = "ios/HasalaCore/Sources/HasalaCore/Resources/TemplatesManifest.swift"
let check = CommandLine.arguments.dropFirst().first == "--check"

func fail(_ message: String) -> Never {
  FileHandle.standardError.write(Data("templates: \(message)\n".utf8))
  exit(1)
}

let fm = FileManager.default
guard let names = try? fm.contentsOfDirectory(atPath: seedDir) else { fail("cannot read \(seedDir); run from the repository root") }
let files = names.filter { $0.hasSuffix(".json") }.sorted()
guard !files.isEmpty else { fail("no seed templates in \(seedDir)") }

if !check { try? fm.createDirectory(atPath: outDir, withIntermediateDirectories: true) }
var rows: [(file: String, id: String, version: Int, sha256: String)] = []
for f in files {
  guard let data = fm.contents(atPath: "\(seedDir)/\(f)") else { fail("cannot read \(f)") }
  guard let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
    let id = obj["id"] as? String, let version = obj["version"] as? Int
  else { fail("\(f) has no string id and integer version") }
  guard f == "\(id).json" else { fail("\(f) holds template \(id); the file must be named <id>.json") }
  let digest = SHA256.hash(data: data).map { String(format: "%02x", $0) }.joined()
  rows.append((f, id, version, digest))
  let dest = "\(outDir)/\(f)"
  if check {
    if fm.contents(atPath: dest) != data { fail("\(dest) differs from \(seedDir)/\(f); run swift ios/tools/templates/sync.swift") }
  } else {
    do { try data.write(to: URL(fileURLWithPath: dest)) } catch { fail("cannot write \(dest): \(error)") }
  }
}
let bundled = ((try? fm.contentsOfDirectory(atPath: outDir)) ?? []).filter { $0.hasSuffix(".json") }.sorted()
if bundled != files {
  if check { fail("\(outDir) holds \(bundled), the seed directory \(files)") }
  for stale in bundled where !files.contains(stale) { try? fm.removeItem(atPath: "\(outDir)/\(stale)") }
}

var manifest = """
  // Code generated by ios/tools/templates/sync.swift. DO NOT EDIT.
  //
  // The bundled bank templates (spec 04 §4.6): templates/<id>.json, copied byte for byte from
  // server/internal/tmpl/seed/. CoreTemplate's BundledTemplates loads a file only when its
  // SHA-256 equals the one here; a mismatch or a dialect failure skips that template and is
  // counted, never guessed around.

  public enum TemplatesManifest {
    public struct Entry: Sendable, Equatable {
      /// The resource name inside `templates/`.
      public let file: String
      public let id: String
      public let version: Int
      /// Lower-case hex SHA-256 of the file's bytes.
      public let sha256: String

      public init(file: String, id: String, version: Int, sha256: String) {
        self.file = file
        self.id = id
        self.version = version
        self.sha256 = sha256
      }
    }

    public static let entries: [Entry] = [

  """
for r in rows {
  manifest += "    Entry(file: \"\(r.file)\", id: \"\(r.id)\", version: \(r.version), sha256: \"\(r.sha256)\"),\n"
}
manifest += "  ]\n}\n"

if check {
  if (try? String(contentsOfFile: manifestPath, encoding: .utf8)) != manifest { fail("\(manifestPath) is stale") }
  print("templates: \(rows.count) bundled templates and the manifest are current")
} else {
  do { try manifest.write(toFile: manifestPath, atomically: true, encoding: .utf8) } catch { fail("cannot write \(manifestPath)") }
  print("templates: copied \(rows.count) templates and wrote \(manifestPath)")
}
